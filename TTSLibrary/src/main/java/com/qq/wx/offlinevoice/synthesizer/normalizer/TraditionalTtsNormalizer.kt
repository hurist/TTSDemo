 * 2. **同音字引導 (Homophone Substitution)**：
 *    利用 TTS 引擎對簡體或特定同音字的發音權重，強制鎖定正確讀音。
 *    - 例：「執著」 (TTS 常誤讀 zhe) -> 替換為「執卓」 (強制讀 zhuó)。
 *
 * 3. **特例優先 (Longest Match First)**：
 *    在替換時，優先匹配長詞，避免短詞規則誤傷長詞。
 *    - 例：優先匹配「沈著冷靜」，後匹配「沈著」。
 *
 */
