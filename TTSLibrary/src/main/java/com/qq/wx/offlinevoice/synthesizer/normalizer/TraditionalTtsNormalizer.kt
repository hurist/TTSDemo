    /**
     * 執行文本標準化處理
     * @param text 原始繁體文本
     * @return 處理後的可朗讀文本（長度嚴格不變）
     */
    fun process(text: String): String {
        if (text.isEmpty()) return text
        var currentText = text

        // 執行詞彙表替換 (Map Replacements)
        // 必須最先執行，因為包含了像「執著->執卓」這樣的強制修正。
        // 如果先執行「著」字正則，這些詞可能會被誤轉成「着」。
        for ((k, v) in SORTED_WORD_REPLACEMENTS) {
            if (currentText.contains(k)) {
                currentText = currentText.replace(k, v)
            }
        }

        // 處理剩餘的「著」 (Regex)
        // 邏輯：
        // - 如果是白名單裡的詞 (著名) -> 保持 "著"
        // - 如果是其他剩下的 "著" (吃著) -> 替換為 "着"
        val m = ZHU_PATTERN.matcher(currentText)
        if (m.find()) {
            val sb = StringBuffer()
            do {
                if (m.group(1) != null) {
                    // 白名單詞彙 -> 保持原樣
                    m.appendReplacement(sb, Matcher.quoteReplacement(m.group(1)))
                } else if (m.group(2) != null) {
                    // 單獨的著 -> 着 (助詞讀 zhe)
                    m.appendReplacement(sb, "着")
                }
            } while (m.find())
            m.appendTail(sb)
            currentText = sb.toString()
        }

        // 單字替換 (Char Array)
        val arr = currentText.toCharArray()
        var changed = false
        for (i in arr.indices) {
            CHAR_REPLACEMENTS[arr[i]]?.let {
                arr[i] = it
                changed = true
            }
        }

        return if (changed) String(arr) else currentText
    }
