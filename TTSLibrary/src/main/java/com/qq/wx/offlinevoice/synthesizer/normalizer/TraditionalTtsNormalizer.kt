    // 優化：預先排序（長詞優先），避免每次 process 重複計算
    private val SORTED_WORD_REPLACEMENTS: List<Pair<String, String>> by lazy {
        RAW_WORD_REPLACEMENTS.entries
            .sortedByDescending { it.key.length }
            .map { it.key to it.value }
            .also { list ->
                // 開發階段安全檢查：確保所有映射都是等長的
                list.forEach { (k, v) ->
                    if (k.length != v.length) {
                        throw IllegalArgumentException("TTS配置錯誤: '$k'(${k.length}) 與 '$v'(${v.length}) 長度不一致！")
                    }
                }
            }
    }

