    // 按 key 长度降序排序，确保最长优先匹配
    private val SORTED_REPLACEMENTS: List<Pair<String, String>> by lazy {
        RAW_REPLACEMENTS.entries
            .sortedByDescending { it.key.length }
            .map { it.key to it.value }
    }

    fun process(text: String): String {
        if (text.isEmpty()) return text
        var current = text
        for ((src, dst) in SORTED_REPLACEMENTS) {
            if (current.contains(src)) {
                current = current.replace(src, dst)
            }
        }
        return current
    }
