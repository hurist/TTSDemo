    // 預先排序（長詞優先），確保 "十里堡" (3字) 優先於 "堡" (1字) 被處理
    private val SORTED_REPLACEMENTS: List<Pair<String, String>> by lazy {
        RAW_REPLACEMENTS.entries
            .sortedByDescending { it.key.length }
            .map { it.key to it.value }
            .also { list ->
                // 開發階段安全檢查
                list.forEach { (k, v) ->
                    if (k.length != v.length) {
                        throw IllegalArgumentException("TTS配置錯誤: '$k' 與 '$v' 長度不一致！")
                    }
                }
            }
    }

    /**
     * 執行文本標準化
     */
    fun process(text: String): String {
        if (text.isEmpty()) return text
        var currentText = text

        // 遍歷有序映射表進行替換
        // 由於 Map 已經按 Key 長度降序排列，這保證了長詞優先匹配
        // (例如 "十里堡" 會在 "堡" 之前被匹配和替換)
        for ((k, v) in SORTED_REPLACEMENTS) {
            if (currentText.contains(k)) {
                currentText = currentText.replace(k, v)
            }
        }
        return currentText
    }
